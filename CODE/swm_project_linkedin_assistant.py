def link_skill(skill_name):
    """Link a skill name to LinkedIn taxonomy category."""
    name_lower = skill_name.lower().strip()

    # 1. Exact alias match
    if name_lower in SKILL_ALIASES:
        return {"match_type": "exact_alias", "category": SKILL_ALIASES[name_lower]}

    # 2. Exact taxonomy match
    for cat in taxonomy_names:
        if name_lower == cat.lower():
            return {"match_type": "exact_taxonomy", "category": cat}

    # 3. Substring match (skill name contains or is contained in a category)
    for cat in taxonomy_names:
        if name_lower in cat.lower() or cat.lower() in name_lower:
            return {"match_type": "substring", "category": cat}

    # 4. Substring match against aliases
    for alias, cat in SKILL_ALIASES.items():
        if alias in name_lower or name_lower in alias:
            return {"match_type": "substring_alias", "category": cat}

    # 5. Fuzzy match
    best_score = 0
    best_match = None

    for alias, cat in SKILL_ALIASES.items():
        score = SequenceMatcher(None, name_lower, alias).ratio()
        if score > best_score:
            best_score = score
            best_match = cat

    for cat in taxonomy_names:
        score = SequenceMatcher(None, name_lower, cat.lower()).ratio()
        if score > best_score:
            best_score = score
            best_match = cat

    if best_score >= 0.6:
        return {"match_type": f"fuzzy ({best_score:.2f})", "category": best_match}

    return {"match_type": "NIL", "category": None}

