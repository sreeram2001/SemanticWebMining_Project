# Try to parse the JSON (handle potential markdown wrapping)
def clean_json(text):
    """Remove markdown code fences if present."""
    text = text.strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[1]  # remove first line
    if text.endswith("```"):
        text = text.rsplit("```", 1)[0]
    return text.strip()

